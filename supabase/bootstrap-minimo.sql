create or replace function public.create_user_with_profile(
  p_id uuid,
  p_email text,
  p_full_name text,
  p_role text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid;
begin
  if auth.uid() is distinct from p_id then
    raise exception 'Authenticated user does not match p_id';
  end if;

  insert into public.users (id, full_name, role, email)
  values (p_id, p_full_name, p_role, lower(trim(p_email)))
  on conflict (id) do update set
    full_name = excluded.full_name,
    role = excluded.role,
    email = excluded.email;

  select up.profile_id
  into v_profile_id
  from public.user_profiles up
  where up.user_id = p_id
    and up.is_owner = true
  limit 1;

  if v_profile_id is null then
    insert into public.profiles (display_name, avatar_url, email, auth_user_id, owner_user_id)
    values (p_full_name, null, lower(trim(p_email)), p_id, p_id)
    returning id into v_profile_id;

    insert into public.user_profiles (user_id, profile_id, is_owner)
    values (p_id, v_profile_id, true)
    on conflict (user_id, profile_id) do update set is_owner = excluded.is_owner;

    insert into public.profile_settings (profile_id)
    values (v_profile_id)
    on conflict (profile_id) do nothing;
  else
    update public.profiles
    set display_name = p_full_name,
        email = lower(trim(p_email)),
        auth_user_id = coalesce(auth_user_id, p_id),
        owner_user_id = coalesce(owner_user_id, p_id)
    where id = v_profile_id;

    insert into public.profile_settings (profile_id)
    values (v_profile_id)
    on conflict (profile_id) do nothing;
  end if;

  return jsonb_build_object(
    'success', true,
    'user_id', p_id,
    'profile_id', v_profile_id
  );
end;
$$;

