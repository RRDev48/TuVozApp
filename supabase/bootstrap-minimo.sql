create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.users (
  id uuid primary key,
  full_name text not null,
  role text not null check (
    role in (
      'self',
      'familiar',
      'maestra_integradora',
      'personal_medico',
      'acompanante_terapeutico'
    )
  ),
  email text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key default gen_random_uuid(),
  display_name text not null,
  avatar_url text,
  email text,
  auth_user_id uuid,
  owner_user_id uuid,
  created_at timestamptz not null default now()
);

create table if not exists public.user_profiles (
  user_id uuid not null references public.users(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  is_owner boolean not null default false,
  created_at timestamptz not null default now(),
  primary key (user_id, profile_id)
);

create index if not exists idx_user_profiles_user on public.user_profiles(user_id);
create index if not exists idx_user_profiles_profile on public.user_profiles(profile_id);

create or replace function public.current_user_linked_to_profile(p_profile_id uuid)
returns boolean
language sql
stable
as $$
  select exists (
    select 1
    from public.user_profiles up
    where up.profile_id = p_profile_id
      and up.user_id = auth.uid()
  );
$$;

create or replace function public.current_user_owns_profile(p_profile_id uuid)
returns boolean
language sql
stable
as $$
  select exists (
    select 1
    from public.user_profiles up
    where up.profile_id = p_profile_id
      and up.user_id = auth.uid()
      and up.is_owner = true
  );
$$;

